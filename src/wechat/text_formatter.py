import re


def format_wechat_text(
    text: str,
) -> str:
    """
    将 AI 输出转换成适合微信公众号
    纯文本消息显示的格式。

    微信客服文本消息不会渲染 Markdown，
    因此这里统一清理常见 Markdown 标记。
    """

    if not text:
        return ""

    result = text.strip()

    # ---------------------------------------------
    # Markdown headings
    # # 标题 / ## 标题
    # ---------------------------------------------

    result = re.sub(
        r"(?m)^\s{0,3}#{1,6}\s+",
        "",
        result,
    )

    # ---------------------------------------------
    # Bold / italic
    # **文字**
    # __文字__
    # ---------------------------------------------

    result = re.sub(
        r"\*\*(.*?)\*\*",
        r"\1",
        result,
        flags=re.DOTALL,
    )

    result = re.sub(
        r"__(.*?)__",
        r"\1",
        result,
        flags=re.DOTALL,
    )

    # ---------------------------------------------
    # Italic
    # *文字*
    # _文字_
    # ---------------------------------------------

    result = re.sub(
        r"(?<!\*)\*([^*\n]+)\*(?!\*)",
        r"\1",
        result,
    )

    result = re.sub(
        r"(?<!_)_([^_\n]+)_(?!_)",
        r"\1",
        result,
    )

    # ---------------------------------------------
    # Markdown links
    # [文字](url) -> 文字（url）
    # ---------------------------------------------

    result = re.sub(
        r"\[([^\]]+)\]\(([^)]+)\)",
        r"\1（\2）",
        result,
    )

    # ---------------------------------------------
    # Inline code
    # `text` -> text
    # ---------------------------------------------

    result = re.sub(
        r"`([^`\n]+)`",
        r"\1",
        result,
    )

    # ---------------------------------------------
    # Block quote
    # > text -> text
    # ---------------------------------------------

    result = re.sub(
        r"(?m)^\s*>\s?",
        "",
        result,
    )

    # ---------------------------------------------
    # Bullet list
    # - xxx / * xxx / + xxx
    # 转换为中文项目符号
    # ---------------------------------------------

    result = re.sub(
        r"(?m)^\s*[-*+]\s+",
        "• ",
        result,
    )

    # ---------------------------------------------
    # Excessive blank lines
    # ---------------------------------------------

    result = re.sub(
        r"\n{3,}",
        "\n\n",
        result,
    )

    return result.strip()